"""The Turn Planner (ADR-0031/0037): the eager whole-turn optimizer and the Pilot's ONE planning
entry point — the **Lethal Solver is its sound top rung**.

A deck-agnostic Pilot Mixin that runs at the start of my turn, BEFORE the tuned Hypothesis scoring.
``plan_turn`` runs the Goal Ladder: the **win rung** first (the Lethal Solver, ADR-0030 — sound,
engine-verified, preempting every heuristic goal), then the heuristic rungs (stabilize-then-KO,
KO-for-prizes, KO-the-key-threat), generated by working backward from a closed, prioritized set of
**Turn Goals** and committing the best — steering this decision toward that line's next step. See
``docs/adr/0037-lethal-solver-is-the-turn-planners-top-rung.md`` and the *Turn Planner* / *Turn
Goal* / *Turn Line* / *Lethal Solver* terms in ``common/CONTEXT.md``.

**Two soundness regimes, one module.** The win rung locks only a GUARANTEED win: min-bound damage
floors, worst-case coins, and the `_engine_confirms_win` verdict-driver (refute drops the candidate;
an unreachable verdict keeps the sound closed-form lock). Everything below it is **heuristic**:
`_simulate_line` auto-resolves coins and its end-of-turn board is trusted for RANKING, never as a
guarantee.

**Layer-on-top (ADR-0031 decision 6).** Below the win rung the Planner commits only when a line
reaches an outcome the tuned per-option scoring would MISS — otherwise it defers, so the proven
default is unchanged.
"""
