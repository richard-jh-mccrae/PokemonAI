#: How many candidate sequences survive each pruning step. **Derived, not tuned** — see the whitelist
#: entry for the arithmetic. Sized against the two measurements already on the record rather than a
#: fresh guess: the post-Option-Equivalence menu width is P50 **6** / P95 **12** / max **23** and the
#: leaf costs P95 **6.57 ms** (Issue #291 §3a, over the 372 corpus frames both gates replay), while
#: the grader's own per-decision FLOOR is **>= 3.0 s** (2 vCPU x ~10 min per player per match,
#: against P95 137 / max 198 decisions per match over the 377 committed native traces).
#:
#: A full run costs at most ``1 + (SEQUENCE_DEPTH - 1) x BEAM_WIDTH`` node expansions of ``width``
#: leaf evaluations each: ``(1 + 3 x 4) x 12 = 156`` leaves ~ **1.03 s** at the P95 leaf, i.e. ~34% of
#: the grader floor. Anchored on the WIDTH half deliberately, the same reasoning `BRANCH_CAP` records:
#: the width is exactly 12 on every run while the millisecond half moves ~10% run-to-run and ~45%
#: between boxes, so a cap keyed to a wall-clock figure is a property of whoever ran it last.
#:
#: **Measured end to end** — `python tools/train/composer_lab.py` over the 374 corpus frames (278
#: composed) at these caps, three fresh processes on an OTHERWISE-IDLE box: per-decision wall-clock
#: **median 24.8-26.5 ms, P95 0.40-0.43 s, max 1.31-1.40 s**. The bound holds with room to spare: the
#: max is ~**44-47%** of the grader's >= 3.0 s per-decision floor and the P95 ~14%.
#:
#: The width is **not** derived from acceptance COVERAGE, and the distinction matters because the two
#: readings disagree: the human-ruled first step lands at rank P50 **2** / P90 **6** / P95 **7** over
#: the 361 gradeable frames, so ``k = 4`` reaches **81.7%** of ruled first steps (k=5 -> 88.1%,
#: k=6 -> 93.6%, k=8 -> 97.5%). Re-deriving the cap from that curve would be a different design call
#: — a coverage budget rather than a time budget — and is not made here.
#:
#: ⚠️ **Two cautions on that number, both learned the hard way.**
#:
#: 1. **The arithmetic above is quoted at the P95 WIDTH, so it under-predicts the widest menus by
#:    ~2x.** The LEAF-EVAL count — which is what the formula actually bounds — is **3515** corpus-wide
#:    and **323** on the widest frame, against the 156 the P95-width form predicts. The same formula
#:    at the observed MAX width gets it right: ``(1 + 3 x 4) x 27 = 351`` against 323. So the honest
#:    statement is *P95 width bounds the P95 decision, not the max one* — quote both or quote neither.
#: 2. **Wall-clock here is only meaningful on an idle machine, and a first pass at these figures was
#:    taken while a full pytest run was in flight.** It read median 35-58 ms / P95 0.58-1.14 s / max
#:    2.45-4.05 s and produced a false alarm — *"the max crosses the grader floor"* — that a review's
#:    independent re-measurement refuted. The tell was available and ignored: the LEAF-EVAL count is
#:    **identical under load and idle**, because the composer is pure, so any spread is the box rather
#:    than the search. Re-measure quiet, and cross-check against leaf evals before believing a
#:    millisecond figure. This is the same trap `BRANCH_CAP` records when it anchors on the WIDTH half.
#:
#: What survives that correction: the cost is **leaf-bound, not beam-bound**. Profiling the widest
#: frame (`86090164|1|turn|6`, 27 options) puts ~100% of the time inside `state_value` — `_hand_legs`
#: -> `needs` -> `_leaf_needs_resolution` -> `pilot._board`. Re-sizing was MEASURED rather than
#: assumed: over ``k`` in {2,3,4} x ``depth`` in {2,3,4} the corpus max does not move outside noise,
#: because leaf evaluations SATURATE at depth 2 (323 at depth 2, 3 and 4 alike — the beam exhausts the
#: legal options before the depth cap binds). Shrinking a cap that does not move the metric would be a
#: constant changed to look responsive, so the caps stand as derived.
#:
#: Machine, because Issue #291 §3a requires a dev-machine number be labelled one: Windows 11,
#: Python 3.11.9, Intel64 Family 6 Model 186 (12 logical cores) — **not** the grader's 2 vCPU.
BEAM_WIDTH = 4

#: Maximum actions in a composed sequence BEFORE its terminal action — i.e. the deepest commutative
#: block the lattice is allowed to reach. 4 bounds one block's a-priori lattice at
#: ``sum(C(n, j) for j <= 4)`` while leaving the worked triple of Issue #263 § *Commutative-block
#: collapse* (an Energy, an evolution and a Tool onto distinct targets) fully inside it with a slot to
#: spare. Truncation is REPORTED (`ComposerResult.stats["depth_truncated"]`), never silent.
#:
#: **It costs nothing over 2 on this corpus, measured**: leaf evaluations on the worst frame are 323
#: at depth 2, 3 and 4 alike, because the beam runs out of legal options before the cap binds. Kept
#: at 4 rather than shrunk to the measured saturation point precisely because that saturation is a
#: fact about THIS corpus's seam coverage (246 of 278 composed frames still carry a refusal), not
#: about the game — a deeper turn becomes reachable the moment Issues #403 / #410 widen the seam, and
#: a cap trimmed to today's coverage would silently bound tomorrow's.
SEQUENCE_DEPTH = 4

#: The epsilon-band admission width, **in prizes** — a candidate within this of the k-th score is
#: admitted alongside the top-k rather than hard-dropped. It is `family_diag.DECIDER_FLOOR`, the
#: corpus-calibrated threshold below which a family cannot be any frame's decider, so a candidate
#: inside the band is one the corpus says nothing separates. Carried under its own name rather than
#: imported, because `tools/` must never be a `src/` dependency; the agreement is asserted by
#: `test_composer.py`.
#:
#: **Swept against the corpus rather than guessed** (`python tools/train/composer_lab.py
#: --epsilon-sweep`, 374 frames, 278 composed). Over epsilon in
#: {0.0, 0.001, 0.005, 0.01, 0.05, 0.1}:
#:
#:     0.0            earned top-k 152/278   band-only 38   agree(ruled) 83   agree(chosen) 50
#:     0.001 - 0.01   earned top-k 150/278   band-only 40   agree(ruled) 82   agree(chosen) 50
#:     0.05 - 0.1     earned top-k 148/278   band-only 42   agree(ruled) 82   agree(chosen) 50
#:
#: ⚠️ **The sweep MOVES now, and its predecessor's not moving was a symptom rather than a result.**
#: Before deferred-target expansion (§S7) every band read identically, which meant the 39 band-only
#: admissions were EXACT ties and not near-ties — on `85046350|0|decision|32` all five options priced
#: exactly 0.0, so there was nothing for a band to be near. Expansion gives those options real
#: deltas, and the sweep separates: three plateaus, 4 frames of movement across the whole range.
#:
#: The value sits in the flat MIDDLE plateau, where 0.001 / 0.005 / 0.01 are indistinguishable. It is
#: not chosen as the argmax: 0.0 reads one agreement better (83 vs 82 of 270), which is a single frame
#: and not evidence that turning the band off is right — the band exists to keep a genuine near-tie
#: with the k-th slot, which is where a good enabling move is most likely to be lost, and one frame
#: is a worse reason to delete that protection than the corpus calibration is to keep it.
#: Re-sweep when the apply seam's coverage widens (246 of 278 frames still carry a refusal), because
#: that is what would make the deltas separate further.
EPSILON = 0.005

def _bench_max(model) -> int:
    """The engine's own ``benchMax`` for my side, or `board_delta`'s fallback.

    Read from the observation rather than assumed, and the fallback is `board_delta`'s so the two
    halves of "is this deploy legal" cannot disagree about the cap — a second constant here is
    exactly the drift ADR-0087 charges for one store over."""
    from common.board_delta import _BENCH_MAX
    obs = getattr(model, "source_obs", None) or {}
    players = ((obs.get("current") or {}).get("players")) or []
    seat = int(getattr(model, "my_index", 0))
    me = players[seat] if 0 <= seat < len(players) and players[seat] else {}
    return int(me.get("benchMax") or _BENCH_MAX)


