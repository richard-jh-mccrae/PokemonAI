"""Expose Claude project skills to Codex without duplicating their instructions."""
from __future__ import annotations

import argparse
import ast
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / ".claude" / "skills"
DESTINATION = REPO / ".agents" / "skills"
GENERATED_NOTICE = "<!-- Generated by tools/sync_agent_skills.py; do not edit. -->"


def _frontmatter(path: Path) -> tuple[str, bool]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"---\r?\n(.*?)\r?\n---(?:\r?\n|$)", text, re.DOTALL)
    if not match:
        raise ValueError(f"{path}: missing YAML frontmatter")
    lines = match.group(1).splitlines()
    values: dict[str, str] = {}
    index = 0
    while index < len(lines):
        field = re.match(r"^(name|description):\s*(.*)$", lines[index])
        if not field:
            index += 1
            continue
        key, raw = field.groups()
        if raw in {">", "|"}:
            block: list[str] = []
            index += 1
            while index < len(lines) and (not lines[index] or lines[index][0].isspace()):
                block.append(lines[index].strip())
                index += 1
            values[key] = (" " if raw == ">" else "\n").join(part for part in block if part)
            continue
        if raw.startswith(("'", '"')):
            raw = ast.literal_eval(raw)
        values[key] = raw
        index += 1
    missing = {"name", "description"} - values.keys()
    if missing:
        raise ValueError(f"{path}: missing {', '.join(sorted(missing))}")
    explicit_only = bool(re.search(
        r"^disable-model-invocation:\s*true\s*$", match.group(1), re.MULTILINE | re.IGNORECASE
    ))
    return _adapter(values["name"], values["description"]), explicit_only


def _adapter(name: str, description: str) -> str:
    canonical = f"../../../.claude/skills/{name}"
    description = description.replace("<", "").replace(">", "")
    if len(description) > 1024:
        description = description[:1021].rsplit(" ", 1)[0] + "..."
    return (
        f"---\nname: {json.dumps(name)}\ndescription: {json.dumps(description, ensure_ascii=False)}\n"
        f"---\n\n{GENERATED_NOTICE}\n\n# Shared project skill\n\n"
        f"Read [`SKILL.md`]({canonical}/SKILL.md) completely, then follow it as the authoritative "
        "workflow.\n\n"
        f"Resolve every relative path in that skill against `{canonical}/`. Translate "
        "host-specific invocation syntax and tool names to Codex equivalents without changing "
        "the workflow, constraints, stop conditions, or outputs.\n"
    )


def _expected() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for source_dir in sorted(path for path in SOURCE.iterdir() if path.is_dir()):
        skill = source_dir / "SKILL.md"
        if not skill.is_file():
            raise ValueError(f"{source_dir}: missing SKILL.md")
        adapter, explicit_only = _frontmatter(skill)
        destination = DESTINATION / source_dir.name
        files[destination / "SKILL.md"] = adapter
        if explicit_only:
            files[destination / "agents" / "openai.yaml"] = (
                "# Generated by tools/sync_agent_skills.py; do not edit.\n"
                "policy:\n  allow_implicit_invocation: false\n"
            )
    return files


def _actual() -> set[Path]:
    if not DESTINATION.exists():
        return set()
    return {path for path in DESTINATION.rglob("*") if path.is_file()}


def sync(*, check: bool) -> list[str]:
    expected = _expected()
    stale = sorted(_actual() - expected.keys())
    changed = sorted(path for path, content in expected.items()
                     if not path.is_file() or path.read_text(encoding="utf-8") != content)
    problems = [str(path.relative_to(REPO)).replace("\\", "/") for path in stale + changed]
    if check or not problems:
        return problems

    for path in stale:
        path.unlink()
    for directory in sorted(
        (path for path in DESTINATION.rglob("*") if path.is_dir()), reverse=True
    ):
        if not any(directory.iterdir()):
            directory.rmdir()
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without changing files")
    args = parser.parse_args()
    problems = sync(check=args.check)
    if args.check and problems:
        print("Codex skill adapters are stale; run: python tools/sync_agent_skills.py")
        print("\n".join(problems))
        return 1
    if not args.check and problems:
        print(f"Synchronized {len(problems)} adapter file(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
